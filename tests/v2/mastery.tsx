import assert from 'node:assert/strict';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as T from 'three';
import { ContractSelector, ContractHUD, ContractDebrief } from '../../app/airrun/mastery-ui';
import { CourseBeacons } from '../../app/airrun/course-beacons';
import { FlightFX } from '../../app/airrun/fx';
import { FlightContract, ReplayRecorder, validReplay, replayPose, personalRival, validContract, courseClock } from '../../app/airrun/mastery';
import { createSim, controls } from './fixtures';
import { useAirrun, validateResult } from '../../app/airrun/state';
import { freshSave } from '../../app/airrun/data';
import { ensureQuests } from '../../app/airrun/progression';

let checks=0;
const check=(value:unknown,label:string)=>{assert.ok(value,label);checks++;};
for(const id of ['precision','velocity','daring'] as const){
    const contract=new FlightContract(id,40,'standard');
    const evidence={perfect:0,boost:0,risk:0},key=id==='precision'?'perfect':id==='velocity'?'boost':'risk';
    evidence[key]=contract.targets[0];
    assert.deepEqual(contract.observe(evidence),[150]);checks++;
    check(contract.observe(evidence).length===0,'Repeated observation never pays twice');
    evidence[key]=contract.targets[2];
    assert.deepEqual(contract.observe(evidence),[300,600]);checks++;
    check(contract.result().bonus===1050&&validContract(contract.result(),evidence),'All three actual milestones conserve rewards');
    check(!validContract({...contract.result(),bonus:2100},evidence),'Multiplier cannot forge doubled contract metadata');
    check(!validContract({...contract.result(),progress:0},evidence),'Tier must agree with achieved progress');
    contract.observe({...evidence,[key]:NaN});check(validContract(contract.result(),evidence),'Corrupt progress cannot change a completed contract');
}
for(const plane of ['skyhawk','falcon','amphibian']){
    const a=createSim({mode:'sortie',plane,seed:71}),b=createSim({mode:'sortie',plane,seed:71});
    a.generate(9000); b.time=97;b.speed=190;b.generate(9000);
    assert.deepEqual(a.encounters,b.encounters);checks++;
    check(a.encounters.every(e=>e.route.length>=3),'Seeded rematches retain actual procedural geometry');
}
const time=courseClock(10000,1);courseClock(50000,1.5);check(courseClock(10000,1)===time&&courseClock(10000,2)===time/2,'Cruise clock is independent of call order and live controls');
const recorder=new ReplayRecorder();
for(let frame=0;frame<=60*180;frame++)recorder.record(frame/60,{x:Math.sin(frame/90)*10,y:24,z:frame/60*40},0);
const replay=recorder.result();
check(replay.samples.length<=400&&replay.samples.length>=360,'Full flight recording is bounded at half-second sampling');
check(validReplay(replay,180,7200),'Finite rounded player trace validates');
const pose=replayPose(replay,90.25)!;check(Math.abs(pose.z-3610)<.01,'Ghost interpolates by actual flight time');
check(replayPose(replay,-1)===null&&replayPose(replay,1000)===null,'Ghost never extrapolates nonexistent flight');
check(!validReplay({...replay,samples:[...replay.samples,[181,0,24,7200,0]]},180,7200),'Replay cannot extend beyond recorded flight');
const copy=recorder.result();copy.samples[0][1]=999;check(recorder.result().samples[0][1]!==999,'Replay snapshots are detached');
const sim=createSim({mode:'sortie',seed:71});
const result=sim.result(true,true);check(validateResult(result),'New partial metadata is save-compatible');
check(!validateResult({...result,contract:{...result.contract!,targets:[1,2,3]}}),'Saved targets must match actual aircraft and difficulty');
check(!validateResult({...result,replay}),'Incomplete results cannot carry a completed personal ghost');
const completed={...result,interrupted:false,eUsed:false,sortie:{...result.sortie!,completed:true},replay};
const identity={seed:71,plane:'skyhawk',level:1,difficulty:'standard' as const,contractId:'precision' as const};
check(personalRival([completed],identity)===completed,'Matching completed normal sortie can become the personal rival');
for(const patch of [{seed:72},{level:2},{difficulty:'expert' as const},{contractId:'daring' as const}])check(!personalRival([completed],{...identity,...patch}),'Different route, equipment, difficulty or contract cannot masquerade as a comparable ghost');
check(!personalRival([{...completed,eUsed:true}],identity),'Hyper-assisted flight cannot become a normal ghost');
const save=ensureQuests(freshSave());save.levels.skyhawk=5;
useAirrun.setState({save,phase:'results',result});useAirrun.getState().retryRoute();
check(useAirrun.getState().seed===71&&useAirrun.getState().runLevel===1&&useAirrun.getState().phase==='preflight','Rematch freezes the original level even after the owned aircraft is upgraded');
useAirrun.setState({phase:'hangar'});useAirrun.getState().start();check(useAirrun.getState().runLevel===null,'A new route restores the owned upgrade level');
const scene=new T.Scene(),marks=new CourseBeacons(scene,sim.plane.span,sim.plane.length);marks.update(sim);
const mesh=marks.root.children.find(c=>c instanceof T.InstancedMesh) as T.InstancedMesh;
check(mesh.count>0&&mesh.count<=100,'Actual route guidance uses a bounded instance pool');
const ghost=marks.root.children.find(c=>c instanceof T.Group) as T.Group;
sim.z=100;
const positionGhost=(gap:number)=>{
    sim.config.rival={score:100,replay:{version:1,samples:[[0,0,24,100+gap,0],[1,0,24,140+gap,0]]}};
    marks.update(sim);
    return (ghost.children[0] as T.Mesh<T.BoxGeometry,T.MeshBasicMaterial>).material.opacity;
};
positionGhost(-4);check(!ghost.visible,'Trailing ghost cannot surround the chase camera');
positionGhost(5);check(!ghost.visible,'Near-overlapping ghost keeps the pilot and route clear');
const faded=positionGhost(16);check(ghost.visible&&faded>0&&faded<.22,'Approaching ghost fades in ahead');
check(positionGhost(60)===.22&&ghost.visible,'Distant comparable ghost remains visible');
positionGhost(351);check(!ghost.visible,'Ghost rendering stays within its bounded view distance');
sim.failed=true;marks.update(sim);check(!marks.root.visible,'Crash never leaves an active target or ghost');marks.dispose();marks.dispose();check(!scene.children.includes(marks.root),'Guide resources detach cleanly and repeated disposal is safe');
const effectsSim=createSim(),fx=new FlightFX(scene,effectsSim.config.catalog),camera=new T.PerspectiveCamera();
camera.position.set(0,24,1);fx.event('flow-bank',{x:0,y:24,z:0},effectsSim);
fx.update(effectsSim,1/60,new T.Group(),[],'balanced',undefined,effectsSim.motionTime,camera);
check(fx.parts.count===0,'Success cubes entering the camera are removed before they obscure the flight');fx.dispose();
const selected=renderToStaticMarkup(<ContractSelector selected="velocity" onSelect={()=>{}} ko/>);
check(selected.includes('aria-pressed="true"')&&selected.includes('직접 가속'),'Selected style and actual objective are explained');
const contract=new FlightContract('precision',40,'standard');contract.observe({perfect:12,boost:0,risk:0});
check(renderToStaticMarkup(<ContractHUD contract={contract.result()} ko/>).includes('목표 완수'),'HUD exposes real completed milestones');
check(renderToStaticMarkup(<ContractDebrief contract={contract.result()} ko/>).includes('1,050'),'Result displays the actual earned subtotal');
console.log(JSON.stringify({masteryChecks:checks,deterministicCourses:3,boundedLocalReplay:true,actualBrowserValidated:false,status:'passed'}));
