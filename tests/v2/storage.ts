import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { freshSave as oldSave, AIRCRAFT as oldAircraft } from '../../app/game/data';
import { parseSave as oldParser } from '../../app/game/store';
import { freshSave, emptyMetrics, AIRCRAFT } from '../../app/airrun/data';
import { ensureQuests } from '../../app/airrun/progression';
import { parseSave, persistSave, useAirrun } from '../../app/airrun/state';
import type { RunResult } from '../../app/airrun/types';
const memory = new Map<string, string>();
Object.defineProperty(globalThis, 'localStorage', { configurable:true, writable:true, value: { getItem: (k: string) => memory.get(k) ?? null, setItem: (k: string, v: string) => memory.set(k, v), removeItem: (k: string) => memory.delete(k) } });
Object.defineProperty(globalThis, 'matchMedia', { configurable:true, writable:true, value: () => ({ matches: false }) });
let checks = 0;
const check = (value: unknown, message: string) => { assert(value, message); checks++; };
const old = oldSave();
old.nickname = 'PILOT LEGACY';
old.coins = 3456;
old.owned = oldAircraft.map(p => p.id);
old.levels = Object.fromEntries(oldAircraft.map((p, i) => [p.id, i + 1]));
old.selected = 7;
old.skins = { skyhawk: ['ocean'] };
old.skinSelected = { skyhawk: 'ocean' };
old.bestDistance = 50000;
old.bestScore = 67000;
old.bestEDistance = 60000;
old.bestEScore = 71000;
old.achievements = ['combo10', 'rings30'];
check(oldParser(old), 'legacy fixture validates');
const migrated = parseSave(old)!;
check(migrated, 'legacy migrates');
check(migrated.coins === 3456 && migrated.levels.falcon === 8 && migrated.owned.length === 8, 'currency and levels preserved');
check(migrated.skins.skyhawk.includes('ocean') && migrated.skinSelected.skyhawk === 'ocean', 'livery preserved');
check(migrated.bests.all.distance === 50000 && migrated.bests.allE.distance === 60000, 'records preserved');
check(migrated.achievements.includes('combo-2') && migrated.achievements.includes('rings-2'), 'paid achievement IDs migrate');
check(parseSave(migrated), 'migrated save round trip');
const checkpoint: RunResult = { id: 'interrupted-run', date: '2026-10-11T00:00:00Z', planeId: 'skyhawk', distance: 600, bonus: 180, score: 780, coins: 3, reward: 24, maxCombo: 1, eUsed: true, practice: false, interrupted: true, reason: 'test', metrics: { ...emptyMetrics(), distance: 600, bonus: 180, coins: 3, maxCombo: 1, time: 15 } };
const save = ensureQuests(freshSave());
save.nickname = 'SAVE PILOT';
save.checkpoint = checkpoint;
await persistSave(save);
useAirrun.setState({ save: ensureQuests(freshSave()) });
await useAirrun.getState().load();
await persistSave(useAirrun.getState().save);
const first = useAirrun.getState().save;
check(first.coins === 24 && first.checkpoint === null && first.settled.includes(checkpoint.id), 'interrupted checkpoint settles exactly once');
await useAirrun.getState().load();
check(useAirrun.getState().save.coins === 24 && useAirrun.getState().save.runs.length === 1, 'second load does not repeat reward');
const activeCheckpoint = { ...checkpoint, id: 'active-flight' };
useAirrun.setState({ phase: 'flying', save: { ...useAirrun.getState().save, checkpoint: activeCheckpoint } });
useAirrun.getState().settle(checkpoint);
check(useAirrun.getState().phase === 'flying' && useAirrun.getState().save.checkpoint?.id === activeCheckpoint.id, 'a stale settlement cannot interrupt or erase the current flight');
useAirrun.setState({ save: { ...useAirrun.getState().save, checkpoint: null } });
for (let i = 0; i < 6; i++) {
    const q = useAirrun.getState().save.quests[i];
    useAirrun.setState({ phase: 'hangar', save: { ...useAirrun.getState().save, quests: useAirrun.getState().save.quests.map(p => p.uid === q.uid ? { ...p, progress: 1e6 } : p) } });
    useAirrun.getState().claimQuest(q.uid);
    const coins = useAirrun.getState().save.coins;
    useAirrun.getState().claimQuest(q.uid);
    check(useAirrun.getState().save.coins === coins, 'quest claim idempotent');
}
await persistSave(useAirrun.getState().save);
const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('voxel-airrun', 1); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
const beforeOutage = ensureQuests(freshSave());
beforeOutage.nickname = 'RESILIENT PILOT';
beforeOutage.coins = 100;
await persistSave(beforeOutage);
const originalTransaction = IDBDatabase.prototype.transaction;
IDBDatabase.prototype.transaction = function () { throw new DOMException('Temporary storage outage', 'UnknownError'); };
const duringOutage = structuredClone(beforeOutage);
duringOutage.coins = 275;
duringOutage.settings = { ...duringOutage.settings, quality: 'balanced', resolutionScale: 1, targetFPS: 30, adaptiveResolution: true, reducedMotion: true, sensitivity: 1.35, leftHanded: true, skipTakeoff: true, volume: .6, music: .3, sfx: .4, language: 'en', control: 'gear' };
await persistSave(duringOutage);
check(memory.has('airrun-save-v3'), 'temporary database outage writes a recoverable fallback');
IDBDatabase.prototype.transaction = originalTransaction;
useAirrun.setState({ save: ensureQuests(freshSave()) });
await useAirrun.getState().load();
check(useAirrun.getState().save.coins === 275, 'newer fallback wins when the database becomes available again');
check(JSON.stringify(useAirrun.getState().save.settings) === JSON.stringify(duringOutage.settings), 'all flight, graphics, sound and accessibility settings survive fallback recovery');
await persistSave(useAirrun.getState().save);
check(!memory.has('airrun-save-v3'), 'successful database commit retires the recovered fallback');
useAirrun.setState({ save: ensureQuests(freshSave()) });
await useAirrun.getState().load();
check(useAirrun.getState().save.coins === 275, 'recovered progress remains after the next database-only load');
const beforeInvalidSetting = useAirrun.getState().save.settings;
useAirrun.getState().settings({ sensitivity: NaN });
check(useAirrun.getState().save.settings === beforeInvalidSetting, 'invalid settings cannot corrupt persistent pilot data');
const invalid = { schema: 3, coins: 'broken', original: 'KEEP ME' };
await new Promise<void>((resolve, reject) => { const tx = db.transaction('pilot', 'readwrite'); tx.objectStore('pilot').put(invalid, 'save-v3'); tx.oncomplete = () => resolve(); tx.onerror = () => reject(tx.error); });
await useAirrun.getState().load();
check(useAirrun.getState().recoveryData !== null, 'invalid original retained for export');
await persistSave(ensureQuests(freshSave()));
const recovered = await new Promise<{original?:string} | undefined>((resolve, reject) => { const r = db.transaction('pilot', 'readonly').objectStore('pilot').get('save-v3-recovery'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error); });
check(recovered?.original === 'KEEP ME', 'invalid original persisted before overwrite');
// Recovery and auto-save must archive the unmodified payload before a repaired
// pilot replaces it. Reading it on the next launch keeps the export usable.
for (let serial = 1; serial <= 4; serial++) {
    const damaged = { ...ensureQuests(freshSave()), serial, nickname: 'PILOT', coins: 1300 + serial, tickets: -7 };
    await new Promise<void>((resolve,reject) => {
        const transaction = db.transaction('pilot','readwrite');
        transaction.objectStore('pilot').put(damaged,'save-v3');
        transaction.oncomplete=()=>resolve(); transaction.onerror=()=>reject(transaction.error);
    });
    await useAirrun.getState().load();
    check(useAirrun.getState().save.coins === damaged.coins,'repair retains currency');
}
for (const [key, expected] of [['save-v3-recovery',4],['save-v3-recovery-2',3],['save-v3-recovery-3',2]] as const) {
    const original = await new Promise<{serial:number;tickets:number}>(resolve => {
        const request = db.transaction('pilot').objectStore('pilot').get(key);
        request.onsuccess=()=>resolve(request.result);
    });
    check(original.serial===expected && original.tickets===-7,'three rotating payloads retain the original damaged fields');
}
db.close();
console.log(JSON.stringify({ storageChecks: checks, legacyPlanes: AIRCRAFT.length, checkpointRewardOnce: true, invalidOriginalPreserved: true, status: 'passed' }));
